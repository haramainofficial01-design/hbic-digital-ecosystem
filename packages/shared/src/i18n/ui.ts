export const supportedLanguages = [
  { code: "en", label: "English", locale: "en-CA", rtl: false },
  { code: "ur", label: "اردو", locale: "ur-PK", rtl: true },
  { code: "fa-AF", label: "دری", locale: "fa-AF", rtl: true },
  { code: "ar", label: "العربية", locale: "ar", rtl: true }
] as const;
const lowerCaseTranslations = new Map(Object.entries(uiTranslations).map(([key, values]) => [key.toLocaleLowerCase("en"), values]));
export function translateUi(language: LanguageCode, source: string): string {
  if (language === "en") return source;
  const index = language === "ur" ? 0 : language === "fa-AF" ? 1 : 2;
  const normalized = source.trim().replace(/\s+/g, " ");
  const translated = (uiTranslations[normalized] ?? lowerCaseTranslations.get(normalized.toLocaleLowerCase("en")))?.[index];
  if (translated) return translated;
  // Keep interpolated amounts exact while translating the surrounding action.
  const donation = normalized.match(/^Donate (CA\$[\d.,]+)$/);
  if (donation) return `${uiTranslations.Donate[index]} ${donation[1]}`;
  const reference = normalized.match(/^(Ayah|Page|Child|Surah|Juz) ([\d:–−-]+)$/);
  if (reference) return `${uiTranslations[reference[1]][index]} ${reference[2]}`;
  const cancel = normalized.match(/^Cancel (.+)'s Quran Academy enrollment\? Future charges for this child will stop\. Any already-paid period remains available until its end\.$/);
  if (cancel) return [
    `${cancel[1]} کا قرآن اکیڈمی داخلہ منسوخ کریں؟ آئندہ ادائیگیاں رک جائیں گی۔ ادا شدہ مدت کے آخر تک رسائی رہے گی۔`,
    `ثبت‌نام اکادمی قرآن ${cancel[1]} لغو شود؟ پرداخت‌های آینده متوقف می‌شود. دسترسی پرداخت‌شده تا پایان دوره باقی می‌ماند.`,
    `هل تريد إلغاء التحاق ${cancel[1]} بأكاديمية القرآن؟ تتوقف الدفعات المستقبلية وتستمر الفترة المدفوعة حتى نهايتها.`
  ][index];
  const suffix = source.match(/^(.*?)(\s*[↗↘→←])$/);
  if (suffix) return translateUi(language, suffix[1]) + suffix[2];
  // Calendar labels contain canonical calculated dates; localize only month
  // names while preserving every number and any manual date adjustment.
  const months = ["Muharram", "Safar", "Rabiʻ I", "Rabiʻ II", "Jumada I", "Jumada II", "Rajab", "Shaʻban", "Ramadan", "Shawwal", "Dhuʻl-Qiʻdah", "Dhuʻl-Hijjah"];
  if (/(?: AH| Hijri)$/.test(normalized) || /^\d{1,2} [A-Za-zʻ’ -]+ \d{4}$/.test(normalized)) {
    let label = normalized;
    for (const month of [...months].sort((a,b) => b.length - a.length)) label = label.replace(month, uiTranslations[month]?.[index] ?? month);
    return label.replace(/\bAH$/, index === 0 ? "ھ" : index === 1 ? "هـ" : "هـ");
  }
  return source;
}
